"""Step 9b: pin the Docker image to the EXACT library versions used to train the models.

The saved models are pickles (joblib) and PyTorch checkpoints. Loading them with different
scikit-learn / LightGBM / NumPy versions can fail or warn, so the image must match this venv.

Run (inside the project venv):  python scripts/freeze_runtime.py
Writes docker/requirements.txt and docker/torch-version.txt
"""
from importlib.metadata import version
from pathlib import Path

RUNTIME = ["numpy", "pandas", "pyarrow", "scikit-learn", "lightgbm", "pyyaml", "joblib",
           "fastapi", "uvicorn", "python-multipart"]

root = Path(__file__).resolve().parents[1] / "docker"
lines = [f"{p}=={version(p)}" for p in RUNTIME]
(root / "requirements.txt").write_text(
    "# Generated by scripts/freeze_runtime.py from the training venv - do not edit by hand.\n"
    + "\n".join(lines) + "\n")
torch_v = version("torch").split("+")[0]
(root / "torch-version.txt").write_text(torch_v + "\n")
print("\n".join(lines))
print(f"torch=={torch_v}  (installed from the CPU-only index)")
